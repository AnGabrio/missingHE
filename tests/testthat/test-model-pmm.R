  expect_shape(pmm$data_set$data_raw$n_mis_c, dim = n.trt)
  expect_length(pmm$data_set$data_raw$n_mis_pat, n.trt)
  expect_named(pmm$data_set$data_raw$n_mis_e, n.trt.names, ignore.case = TRUE)
  expect_named(pmm$data_set$data_raw$n_mis_c, n.trt.names, ignore.case = TRUE)
  expect_named(pmm$data_set$data_raw$n_mis_pat, n.trt.names, ignore.case = TRUE)
