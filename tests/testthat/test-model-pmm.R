  expect_type(pmm$model_output$imputed_trt$effects$avg, "list")
  expect_length(pmm$model_output$imputed_trt$effects$avg, n.trt)
  expect_named(pmm$model_output$imputed_trt$effects$avg, n.trt.names, ignore.case = TRUE)
  expect_type(pmm$model_output$imputed_trt$effects$ql, "list")
  expect_length(pmm$model_output$imputed_trt$effects$ql, n.trt)
  expect_named(pmm$model_output$imputed_trt$effects$ql, n.trt.names, ignore.case = TRUE)
  expect_type(pmm$model_output$imputed_trt$effects$qu, "list")
  expect_length(pmm$model_output$imputed_trt$effects$qu, n.trt)
  expect_named(pmm$model_output$imputed_trt$effects$qu, n.trt.names, ignore.case = TRUE)
  expect_type(pmm$model_output$imputed_trt$effects$index, "list")
  expect_length(pmm$model_output$imputed_trt$effects$index, n.trt)
  expect_named(pmm$model_output$imputed_trt$effects$index, n.trt.names, ignore.case = TRUE)
  expect_type(pmm$model_output$imputed_trt$costs, "list")
  expect_length(pmm$model_output$imputed_trt$costs, 4)
  expect_named(pmm$model_output$imputed_trt$costs, c("avg", "ql", "qu", "index"))
  expect_type(pmm$model_output$imputed_trt$costs$avg, "list")
  expect_length(pmm$model_output$imputed_trt$costs$avg, n.trt)
