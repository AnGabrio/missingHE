  expect_type(pmm$data_set, "list")
  expect_named(pmm$data_set, c("data_raw", "model_formula"))

  expect_length(pmm$mod_est, 3)
  expect_type(pmm$mod_est, "list")
  expect_named(pmm$mod_est, c("model.eff", "model.cost", "model.pattern"))

  expect_equal(pmm$restriction, "CC")

  expect_length(pmm$call, 8)
  expect_type(pmm$call, "language")
  expect_named(pmm$call, c("", "model.eff", "model.cost", "data", "dist_e", "dist_c", "type", "n.iter"))

  expect_length(pmm$cea, 24)
  expect_type(pmm$cea, "list")
