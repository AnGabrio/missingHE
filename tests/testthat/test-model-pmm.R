  expect_equal(pmm$data_set$data_raw$c, MenSSv2$c, ignore_attr = TRUE)
  expect_vector(pmm$data_set$data_raw$me)
  expect_vector(pmm$data_set$data_raw$mc)
  expect_length(pmm$data_set$data_raw$me, n.ind)
  expect_length(pmm$data_set$data_raw$mc, n.ind)
  expect_vector(pmm$data_set$data_raw$n_obs_e)
  expect_vector(pmm$data_set$data_raw$n_obs_c)
  expect_vector(pmm$data_set$data_raw$n_obs_pat)
  expect_length(pmm$data_set$data_raw$n_obs_e, n.trt)
  expect_length(pmm$data_set$data_raw$n_obs_c, n.trt)
  expect_length(pmm$data_set$data_raw$n_obs_pat, n.trt)
  expect_named(pmm$data_set$data_raw$n_obs_e, n.trt.names, ignore.case = TRUE)
  expect_named(pmm$data_set$data_raw$n_obs_c, n.trt.names, ignore.case = TRUE)
  expect_named(pmm$data_set$data_raw$n_obs_pat, n.trt.names, ignore.case = TRUE)
