  expect_null(pmm$data_set$data_raw$n_clus_e)
  expect_length(pmm$data_set$data_raw$trt_pos_e, 1)
  expect_length(pmm$data_set$data_raw$trt_pos_c, 1)
  expect_length(pmm$data_set$data_raw$trt_pos_me, 1)
  expect_length(pmm$data_set$data_raw$trt_pos_mc, 1)
  expect_type(pmm$data_set$data_raw$trt_index, "list")
  expect_length(pmm$data_set$data_raw$trt_index, n.trt)
  expect_named(pmm$data_set$data_raw$trt_index, n.trt.names, ignore.case = TRUE)
  expect_type(pmm$data_set$data_raw$efft, "list")
  expect_named(pmm$data_set$data_raw$efft, n.trt.names, ignore.case = TRUE)
