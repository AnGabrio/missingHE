  expect_null(pmm$data_set$data_raw$x_c_random)
  expect_null(pmm$data_set$data_raw$clusn_e)
  expect_null(pmm$data_set$data_raw$clusn_c)
  expect_null(pmm$data_set$data_raw$clus_e_lev)
  expect_null(pmm$data_set$data_raw$clus_c_lev)
  expect_equal(pmm$data_set$model_formula$mf_model.e_fixed, model.eff, ignore_attr = TRUE)
  expect_equal(pmm$data_set$model_formula$mf_model.c_fixed, model.cost, ignore_attr = TRUE)
  expect_equal(pmm$data_set$model_formula$mf_model.e_random, e ~ 0, ignore_attr = TRUE)
  expect_equal(pmm$data_set$model_formula$mf_model.c_random, c ~ 0, ignore_attr = TRUE)

  expect_length(pmm$model_output, 22)
  expect_type(pmm$model_output, "list")
  expect_named(pmm$model_output, c("summary", "model", "mean_effects", "mean_costs", "sd_effects",
                                  "sd_costs", "effects_fixed", "costs_fixed", "p_pattern",
                                  "effects_random", "costs_random", "imputed", "imputed_trt", "loglik", "type",
                                  "method", "ind_fixed", "ind_random", "dist_e", "dist_c", "filein", "d_mod"))
  expect_shape(pmm$model_output$summary, ncol = 9)
  expect_type(pmm$model_output$model, "list")
  expect_shape(pmm$model_output$mean_effects, dim = c(n.iter, n.trt))
  expect_shape(pmm$model_output$mean_costs, dim = c(n.iter, n.trt))
  expect_shape(pmm$model_output$sd_effects, nrow = n.iter)
  expect_shape(pmm$model_output$sd_costs, nrow = n.iter)
  expect_shape(pmm$model_output$effects_fixed, nrow = n.iter)
  expect_shape(pmm$model_output$costs_fixed, nrow = n.iter)
  expect_shape(pmm$model_output$p_pattern, nrow = n.iter)
  expect_equal(pmm$model_output$effects_random, pmm$data_set$data_raw$x_e_random)
  expect_equal(pmm$model_output$costs_random, pmm$data_set$data_raw$x_c_random)
